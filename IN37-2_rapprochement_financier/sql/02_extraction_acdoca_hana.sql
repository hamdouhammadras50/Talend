-- =====================================================================
-- IN37-2 / IT-19934 - Rapprochement financier
-- Requêtes d'extraction S/4HANA (à coller dans les tDBInput du job)
--
-- Placeholders à remplacer par les variables de contexte Talend :
--   ${MANDT}       -> context.SAP_MANDT        (ex : '100')
--   ${LAST_TS}     -> context.LAST_TS          (ex : 20261018220000)
--   ${CURRENT_TS}  -> context.CURRENT_TS       (ex : 20261019220000)
--   ${LAST_DATE}   -> context.LAST_TS.substring(0,8)  (format DATS AAAAMMJJ)
--
-- Remarques :
--   * RLDNR = '0L' : on ne lit que le ledger principal (sinon doublons).
--   * XREF2 / XREF3 ne sont pas dans ACDOCA -> jointure BSEG.
--   * RACCT est stocké avec des zéros à gauche -> LTRIM(RACCT,'0').
--   * Les sets peuvent contenir des intervalles (VALOPTION = 'BT') ;
--     ici on gère EQ et BT via VALFROM / VALTO.
--   * Le bloc WITH (périmètre LTRF : SOC, PDV, PRC, KST, CPT, FRN) est
--     répété dans chaque requête car chaque tDBInput est autonome.
-- =====================================================================


-- =====================================================================
-- FLUX 1 : pièces NON rapprochées (AUGBL vide) - delta sur TIMESTAMP
-- =====================================================================
WITH
  SOC AS (SELECT VALFROM AS BUKRS_FROM, VALTO AS BUKRS_TO, VALOPTION FROM SETLEAF
           WHERE MANDT = '${MANDT}' AND SETCLASS = '0000' AND SETNAME = 'ZFI_LTRF_BUKRS'),
  PDV AS (SELECT DISTINCT W.WERKS FROM T001K K
            JOIN T001W W ON W.MANDT = K.MANDT AND W.BWKEY = K.BWKEY
           WHERE K.MANDT = '${MANDT}' AND W.VLFKZ = 'A'
             AND EXISTS (SELECT 1 FROM SOC S WHERE K.BUKRS = S.BUKRS_FROM
                          OR (S.VALOPTION = 'BT' AND K.BUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))),
  PRC AS (SELECT DISTINCT PRCTR FROM ZREF_CP WHERE MANDT = '${MANDT}' AND WERKS IN (SELECT WERKS FROM PDV)),
  KST AS (SELECT DISTINCT KOSTL FROM CSKS WHERE MANDT = '${MANDT}' AND PRCTR IN (SELECT PRCTR FROM PRC)
             AND DATBI >= TO_VARCHAR(CURRENT_DATE, 'YYYYMMDD')),
  CPT AS (SELECT LTRIM(VALFROM,'0') AS RACCT_FROM, LTRIM(VALTO,'0') AS RACCT_TO, VALOPTION FROM SETLEAF
           WHERE MANDT = '${MANDT}' AND SETCLASS = '0000' AND SETNAME = 'ZFI_LTRF_RAPPRO_FI_RACCT'),
  FRN AS (SELECT LOW AS LIFNR FROM TVARVC WHERE MANDT = '${MANDT}' AND NAME = 'ZFI_LTRF_FF_LIFNR')
SELECT
    A.RBUKRS, A.GJAHR, A.BELNR, A.BUZEI, A.DOCLN,
    A.BLDAT, A.BUDAT, A.TIMESTAMP,
    A.BLART, LTRIM(A.RACCT,'0') AS RACCT, A.PRCTR, A.RCNTR,
    A.HSL, A.SGTXT,
    B.XREF2, B.XREF3,
    A.AUGBL, A.AUGDT
FROM ACDOCA A
LEFT JOIN BSEG B
       ON B.MANDT = A.RCLNT AND B.BUKRS = A.RBUKRS
      AND B.GJAHR = A.GJAHR AND B.BELNR = A.BELNR AND B.BUZEI = A.BUZEI
WHERE A.RCLNT = '${MANDT}'
  AND A.RLDNR = '0L'
  AND EXISTS (SELECT 1 FROM SOC S WHERE A.RBUKRS = S.BUKRS_FROM
               OR (S.VALOPTION = 'BT' AND A.RBUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))
  AND A.AUGBL = ''
  AND A.TIMESTAMP >  ${LAST_TS}
  AND A.TIMESTAMP <= ${CURRENT_TS}
  AND (
        ( A.BLART IN ('ZR','RB','YJ')
          AND A.PRCTR IN (SELECT PRCTR FROM PRC)
          AND EXISTS (SELECT 1 FROM CPT C WHERE LTRIM(A.RACCT,'0') = C.RACCT_FROM
                       OR (C.VALOPTION = 'BT' AND LTRIM(A.RACCT,'0') BETWEEN C.RACCT_FROM AND C.RACCT_TO)) )
     OR ( A.BLART = 'FF'
          AND A.RCNTR IN (SELECT KOSTL FROM KST)
          AND A.LIFNR IN (SELECT LIFNR FROM FRN) )
      );


-- =====================================================================
-- FLUX 2 : pièces RAPPROCHÉES (AUGBL non vide) - delta sur AUGDT
-- + calcul des écarts RG04 à RG07 sur la même pièce
-- =====================================================================
WITH
  SOC AS (SELECT VALFROM AS BUKRS_FROM, VALTO AS BUKRS_TO, VALOPTION FROM SETLEAF
           WHERE MANDT = '${MANDT}' AND SETCLASS = '0000' AND SETNAME = 'ZFI_LTRF_BUKRS'),
  PDV AS (SELECT DISTINCT W.WERKS FROM T001K K
            JOIN T001W W ON W.MANDT = K.MANDT AND W.BWKEY = K.BWKEY
           WHERE K.MANDT = '${MANDT}' AND W.VLFKZ = 'A'
             AND EXISTS (SELECT 1 FROM SOC S WHERE K.BUKRS = S.BUKRS_FROM
                          OR (S.VALOPTION = 'BT' AND K.BUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))),
  PRC AS (SELECT DISTINCT PRCTR FROM ZREF_CP WHERE MANDT = '${MANDT}' AND WERKS IN (SELECT WERKS FROM PDV)),
  KST AS (SELECT DISTINCT KOSTL FROM CSKS WHERE MANDT = '${MANDT}' AND PRCTR IN (SELECT PRCTR FROM PRC)
             AND DATBI >= TO_VARCHAR(CURRENT_DATE, 'YYYYMMDD')),
  CPT AS (SELECT LTRIM(VALFROM,'0') AS RACCT_FROM, LTRIM(VALTO,'0') AS RACCT_TO, VALOPTION FROM SETLEAF
           WHERE MANDT = '${MANDT}' AND SETCLASS = '0000' AND SETNAME = 'ZFI_LTRF_RAPPRO_FI_RACCT'),
  FRN AS (SELECT LOW AS LIFNR FROM TVARVC WHERE MANDT = '${MANDT}' AND NAME = 'ZFI_LTRF_FF_LIFNR'),
  SEL AS (
    SELECT A.*
      FROM ACDOCA A
     WHERE A.RCLNT = '${MANDT}'
       AND A.RLDNR = '0L'
       AND EXISTS (SELECT 1 FROM SOC S WHERE A.RBUKRS = S.BUKRS_FROM
                    OR (S.VALOPTION = 'BT' AND A.RBUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))
       AND A.AUGBL <> ''
       AND A.AUGDT >= '${LAST_DATE}'
       AND (
             ( A.BLART IN ('ZR','RB','YJ')   -- YJ = "XX à confirmer par F. Fixot"
               AND A.RCNTR IN (SELECT KOSTL FROM KST)
               AND EXISTS (SELECT 1 FROM CPT C WHERE LTRIM(A.RACCT,'0') = C.RACCT_FROM
                            OR (C.VALOPTION = 'BT' AND LTRIM(A.RACCT,'0') BETWEEN C.RACCT_FROM AND C.RACCT_TO)) )
          OR ( A.BLART = 'FF'
               AND A.RCNTR IN (SELECT KOSTL FROM KST)
               AND A.LIFNR IN (SELECT LIFNR FROM FRN) )
           )
  ),
  ECART AS (  -- RG04 / RG05 / RG06 / RG07 : lignes d'écart de la même pièce
    SELECT E.RBUKRS, E.GJAHR, E.BELNR,
           ABS(SUM(CASE WHEN LTRIM(E.RACCT,'0') = '51100003' THEN E.HSL ELSE 0 END)) AS LITIGE_BANCAIRE,
           ABS(SUM(CASE WHEN LTRIM(E.RACCT,'0') = '65171000' THEN E.HSL ELSE 0 END)) AS IMPUTATION_GERANT,
           ABS(SUM(CASE WHEN LTRIM(E.RACCT,'0') = '62780002' THEN E.HSL ELSE 0 END)) AS FRAIS_CB,
           ABS(SUM(CASE WHEN LTRIM(E.RACCT,'0') = '75601000' THEN E.HSL ELSE 0 END)) AS DIFFERENCE_CHANGE,
           MAX(CASE WHEN LTRIM(E.RACCT,'0') = '65171000' THEN 1 ELSE 0 END)           AS HAS_IMPUT_GERANT,
           MAX(CASE WHEN LTRIM(E.RACCT,'0') IN ('51100003','65171000','62780002','75601000')
                    THEN 1 ELSE 0 END)                                               AS HAS_ECART
      FROM ACDOCA E
      JOIN (SELECT DISTINCT RBUKRS, GJAHR, BELNR FROM SEL) D
        ON D.RBUKRS = E.RBUKRS AND D.GJAHR = E.GJAHR AND D.BELNR = E.BELNR
     WHERE E.RCLNT = '${MANDT}' AND E.RLDNR = '0L'
     GROUP BY E.RBUKRS, E.GJAHR, E.BELNR
  ),
  MOTIF AS (  -- RG05 : SGTXT du 1er enregistrement accédé sur 65171000
    SELECT RBUKRS, GJAHR, BELNR, SGTXT AS MOTIF_IMPUTATION
      FROM (SELECT E.RBUKRS, E.GJAHR, E.BELNR, E.SGTXT,
                   ROW_NUMBER() OVER (PARTITION BY E.RBUKRS, E.GJAHR, E.BELNR ORDER BY E.DOCLN) AS RN
              FROM ACDOCA E
              JOIN (SELECT DISTINCT RBUKRS, GJAHR, BELNR FROM SEL) D
                ON D.RBUKRS = E.RBUKRS AND D.GJAHR = E.GJAHR AND D.BELNR = E.BELNR
             WHERE E.RCLNT = '${MANDT}' AND E.RLDNR = '0L'
               AND LTRIM(E.RACCT,'0') = '65171000')
     WHERE RN = 1
  )
SELECT
    S.RBUKRS, S.GJAHR, S.BELNR, S.BUZEI, S.DOCLN,
    S.BLDAT, S.BUDAT, S.TIMESTAMP,
    S.BLART, LTRIM(S.RACCT,'0') AS RACCT, S.PRCTR, S.RCNTR,
    S.HSL, S.SGTXT,
    B.XREF2, B.XREF3,
    S.AUGBL, S.AUGDT,
    COALESCE(E.LITIGE_BANCAIRE, 0)   AS LITIGE_BANCAIRE,
    COALESCE(E.IMPUTATION_GERANT, 0) AS IMPUTATION_GERANT,
    COALESCE(E.FRAIS_CB, 0)          AS FRAIS_CB,
    COALESCE(E.DIFFERENCE_CHANGE, 0) AS DIFFERENCE_CHANGE,
    COALESCE(E.HAS_IMPUT_GERANT, 0)  AS HAS_IMPUT_GERANT,
    COALESCE(E.HAS_ECART, 0)         AS HAS_ECART,
    M.MOTIF_IMPUTATION
FROM SEL S
LEFT JOIN BSEG B
       ON B.MANDT = S.RCLNT AND B.BUKRS = S.RBUKRS
      AND B.GJAHR = S.GJAHR AND B.BELNR = S.BELNR AND B.BUZEI = S.BUZEI
LEFT JOIN ECART E ON E.RBUKRS = S.RBUKRS AND E.GJAHR = S.GJAHR AND E.BELNR = S.BELNR
LEFT JOIN MOTIF M ON M.RBUKRS = S.RBUKRS AND M.GJAHR = S.GJAHR AND M.BELNR = S.BELNR;


-- =====================================================================
-- FLUX 3 : ANNULATIONS de rapprochement (BLART = 'RG', XREVERSING = 'X')
-- =====================================================================
WITH
  SOC AS (SELECT VALFROM AS BUKRS_FROM, VALTO AS BUKRS_TO, VALOPTION FROM SETLEAF
           WHERE MANDT = '${MANDT}' AND SETCLASS = '0000' AND SETNAME = 'ZFI_LTRF_BUKRS'),
  PDV AS (SELECT DISTINCT W.WERKS FROM T001K K
            JOIN T001W W ON W.MANDT = K.MANDT AND W.BWKEY = K.BWKEY
           WHERE K.MANDT = '${MANDT}' AND W.VLFKZ = 'A'
             AND EXISTS (SELECT 1 FROM SOC S WHERE K.BUKRS = S.BUKRS_FROM
                          OR (S.VALOPTION = 'BT' AND K.BUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))),
  PRC AS (SELECT DISTINCT PRCTR FROM ZREF_CP WHERE MANDT = '${MANDT}' AND WERKS IN (SELECT WERKS FROM PDV)),
  KST AS (SELECT DISTINCT KOSTL FROM CSKS WHERE MANDT = '${MANDT}' AND PRCTR IN (SELECT PRCTR FROM PRC)
             AND DATBI >= TO_VARCHAR(CURRENT_DATE, 'YYYYMMDD'))
SELECT
    A.RBUKRS, A.GJAHR, A.BELNR, A.DOCLN,
    A.AWORG, A.AWREF, A.AWITEM,
    A.BLDAT, A.BUDAT, A.TIMESTAMP
FROM ACDOCA A
WHERE A.RCLNT = '${MANDT}'
  AND A.RLDNR = '0L'
  AND EXISTS (SELECT 1 FROM SOC S WHERE A.RBUKRS = S.BUKRS_FROM
               OR (S.VALOPTION = 'BT' AND A.RBUKRS BETWEEN S.BUKRS_FROM AND S.BUKRS_TO))
  AND A.RCNTR IN (SELECT KOSTL FROM KST)
  AND A.BLART = 'RG'
  AND A.XREVERSING = 'X'
  AND A.TIMESTAMP >  ${LAST_TS}
  AND A.TIMESTAMP <= ${CURRENT_TS};
